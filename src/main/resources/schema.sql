-- JobRunr MCP hub: accounts, tokens and connected instances. Portable between H2 and PostgreSQL.
-- The hub never stores tool arguments, tool results or job data.

CREATE TABLE IF NOT EXISTS hub_accounts (
    id          VARCHAR(36)   PRIMARY KEY,
    email       VARCHAR(320)  NOT NULL UNIQUE,
    name        VARCHAR(200)  NOT NULL,
    company     VARCHAR(200)  NOT NULL,
    job_role    VARCHAR(200),
    use_case    VARCHAR(1000),
    cluster_id  VARCHAR(64),
    is_pro      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP     NOT NULL,
    verified_at TIMESTAMP
);

-- Existing H2 and PostgreSQL installations were created before is_pro existed.
ALTER TABLE hub_accounts ADD COLUMN IF NOT EXISTS is_pro BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS hub_tokens (
    id           VARCHAR(36)  PRIMARY KEY,
    account_id   VARCHAR(36)  NOT NULL,
    kind         VARCHAR(16)  NOT NULL,
    scope        VARCHAR(16),
    token_hash   VARCHAR(64)  NOT NULL UNIQUE,
    hint         VARCHAR(8)   NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    revoked_at   TIMESTAMP
);

-- One current token of each kind per account, independent of the historical rows above.
-- Backfill existing installations on startup, selecting the newest still-active token.
CREATE TABLE IF NOT EXISTS hub_current_tokens (
    account_id VARCHAR(36) NOT NULL,
    kind       VARCHAR(16) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    PRIMARY KEY (account_id, kind)
);

INSERT INTO hub_current_tokens (account_id, kind, token_hash)
SELECT recent.account_id, recent.kind, recent.token_hash
FROM (
    SELECT t.account_id, t.kind, t.token_hash,
           ROW_NUMBER() OVER (PARTITION BY t.account_id, t.kind ORDER BY t.created_at DESC, t.id DESC) AS rn
    FROM hub_tokens t
    WHERE t.revoked_at IS NULL
) recent
WHERE recent.rn = 1
  AND NOT EXISTS (
      SELECT 1 FROM hub_current_tokens slot
      WHERE slot.account_id = recent.account_id AND slot.kind = recent.kind
  );

CREATE TABLE IF NOT EXISTS hub_magic_links (
    token_hash VARCHAR(64) PRIMARY KEY,
    account_id VARCHAR(36) NOT NULL,
    expires_at TIMESTAMP   NOT NULL,
    used_at    TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hub_sessions (
    token_hash VARCHAR(64) PRIMARY KEY,
    account_id VARCHAR(36) NOT NULL,
    expires_at TIMESTAMP   NOT NULL
);

-- Legacy one-snapshot-per-account table, retained for upgrades from earlier releases.
CREATE TABLE IF NOT EXISTS hub_instances (
    account_id         VARCHAR(36)  PRIMARY KEY,
    cluster_id         VARCHAR(64),
    jobrunr_version    VARCHAR(40),
    java_version       VARCHAR(40),
    framework          VARCHAR(40),
    storage_provider   VARCHAR(100),
    redaction          BOOLEAN,
    servers            INT,
    recurring_jobs     BIGINT,
    jobs_scheduled     BIGINT,
    jobs_enqueued      BIGINT,
    jobs_processing    BIGINT,
    jobs_failed        BIGINT,
    jobs_succeeded     BIGINT,
    first_connected_at TIMESTAMP,
    snapshot_at        TIMESTAMP
);

-- Pro accounts can have several clusters. A snapshot belongs to the cluster it came from,
-- so background refreshes cannot overwrite another cluster's account-page numbers.
CREATE TABLE IF NOT EXISTS hub_cluster_snapshots (
    account_id         VARCHAR(36)  NOT NULL,
    cluster_id         VARCHAR(64)  NOT NULL,
    jobrunr_version    VARCHAR(40),
    java_version       VARCHAR(40),
    framework          VARCHAR(40),
    storage_provider   VARCHAR(100),
    redaction          BOOLEAN,
    servers            INT,
    recurring_jobs     BIGINT,
    jobs_scheduled     BIGINT,
    jobs_enqueued      BIGINT,
    jobs_processing    BIGINT,
    jobs_failed        BIGINT,
    jobs_succeeded     BIGINT,
    first_connected_at TIMESTAMP,
    snapshot_at        TIMESTAMP,
    PRIMARY KEY (account_id, cluster_id)
);

INSERT INTO hub_cluster_snapshots (
    account_id, cluster_id, jobrunr_version, java_version, framework, storage_provider, redaction,
    servers, recurring_jobs, jobs_scheduled, jobs_enqueued, jobs_processing, jobs_failed,
    jobs_succeeded, first_connected_at, snapshot_at
)
SELECT legacy.account_id, legacy.cluster_id, legacy.jobrunr_version, legacy.java_version,
       legacy.framework, legacy.storage_provider, legacy.redaction, legacy.servers,
       legacy.recurring_jobs, legacy.jobs_scheduled, legacy.jobs_enqueued,
       legacy.jobs_processing, legacy.jobs_failed, legacy.jobs_succeeded,
       legacy.first_connected_at, legacy.snapshot_at
FROM hub_instances legacy
WHERE legacy.cluster_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM hub_cluster_snapshots existing
      WHERE existing.account_id = legacy.account_id AND existing.cluster_id = legacy.cluster_id
  );

CREATE TABLE IF NOT EXISTS hub_tool_calls (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  VARCHAR(36)  NOT NULL,
    tool_name   VARCHAR(64)  NOT NULL,
    success     BOOLEAN      NOT NULL,
    latency_ms  BIGINT       NOT NULL,
    user_agent  VARCHAR(300),
    occurred_at TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS hub_lead_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  VARCHAR(36)  NOT NULL,
    event       VARCHAR(64)  NOT NULL,
    detail      VARCHAR(500),
    occurred_at TIMESTAMP    NOT NULL
);
